import util::*;

module autogen_top_wrapper #(
    parameter reg   [(8*VERSION_CHARS)-1:0] VERSION                 = \"${build_version}\",
    parameter int                           VERSION_LEN             = ${build_version_len},

    parameter int                           CLK_FREQUENCY_MHZ       = ${clock_frequency_mhz},
    parameter int                           PUSHBUTTON0_AS_RESET    = ${pushbutton_reset},
    parameter int                           EMBEDDED_LOGIC_ANALYZER = ${embedded_logic_analyzer}

) (
    input                               pad_clk_27Mhz,

    input   [2:1]                       pad_user_buttons_n,
    output                              pad_led_n,
    inout   [16:1]                      pad_io,
        // NOTE: Indexed to match PIN
        // numbers...
    inout   [17:0]                      pad_cpu,

    // NOTE: these ports are needed,
    // or the PSRAM IP will not
    // compile...
    output  [CS_WIDTH-1:0]              O_psram_ck,
    output  [CS_WIDTH-1:0]              O_psram_ck_n,
    inout   [CS_WIDTH-1:0]              IO_psram_rwds,
    inout   [DQ_WIDTH-1:0]              IO_psram_dq,
    output  [CS_WIDTH-1:0]              O_psram_reset_n,
    output  [CS_WIDTH-1:0]              O_psram_cs_n,

    // NOTE: these ports are needed,
    // for the GW_JTAG module to be
    // wired up transparently...
    input   wire                        tms_pad_i,
    input   wire                        tck_pad_i,
    input   wire                        tdi_pad_i,
    output  wire                        tdo_pad_o
);
localparam VERSION_CHARS    = 63;
localparam DQ_WIDTH         = 16;
localparam CS_WIDTH         = 2;


    // ----------------------------------------------
    //  Internal signals
    // ----------------------------------------------

    reg                 i_sysclk;
    reg                 i_sysclk_resetn  = 1'b0;

    reg                 i_microsecond_tick;
    reg                 i_millisecond_tick;
    reg                 i_second_tick;

    reg         [11:0]  i_millisecond_counter;

    reg         [15:0]  i_user_probe;

    reg                 i_jtag_activity;

    reg         [31:0]  i_cpu_addr;
    reg         [31:0]  i_cpu_wdata;
    reg         [3:0]   i_cpu_wstrb;
    reg         [31:0]  i_cpu_rdata;
    reg                 i_cpu_valid;
    reg                 i_cpu_ready;

    reg         [31:0]  i_ram_addr;
    reg         [31:0]  i_ram_wdata;
    reg         [3:0]   i_ram_wstrb;
    reg         [31:0]  i_ram_rdata;
    reg                 i_ram_valid;
    reg                 i_ram_ready;

    reg                 i_top_led;
    reg         [2:0]   i_ela_led;

    localparam PROBE_BUS_W   = 128;
    localparam PROBE_WATCH_W = 128;
        // NOTE: must match the localparams
        // of the same name in top.sv

    wire [PROBE_BUS_W-1:0]      i_probe_bus;
    wire [PROBE_WATCH_W-1:0]    i_probe_watch;
    wire [7:0]                  i_eio_out;


    // ----------------------------------------------
    //  Implementation
    // ----------------------------------------------

    top #(
        .VERSION                    (VERSION),
        .CLK_FREQUENCY_MHZ          (CLK_FREQUENCY_MHZ),
        .PUSHBUTTON0_AS_RESET       (PUSHBUTTON0_AS_RESET)
    ) top_inst (

        // ---------------- pads ----------------

        .clk_27Mhz                  (pad_clk_27Mhz),

        .user_pushbutton0_n         (pad_user_buttons_n[1]),
        .user_pushbutton1_n         (pad_user_buttons_n[2]),

        .led                        (i_top_led),

        .cpu_data_async             (pad_cpu[15:0]),
        .cpu_clk_async              (pad_cpu[16]),
        .cpu_wr_async               (pad_cpu[17]),

        .psram_ck                   (O_psram_ck),
        .psram_ck_n                 (O_psram_ck_n),
        .psram_rwds                 (IO_psram_rwds),
        .psram_dq                   (IO_psram_dq),
        .psram_reset_n              (O_psram_reset_n),
        .psram_cs_n                 (O_psram_cs_n),


        // -------------- fabric --------------

        .sysclk                     (i_sysclk),
        .sysclk_resetn              (i_sysclk_resetn),

        .microsecond_tick           (i_microsecond_tick),
        .millisecond_tick           (i_millisecond_tick),
        .second_tick                (i_second_tick),

        .millisecond_counter        (i_millisecond_counter),


        // -------------- cpu --------------

        .cpu_addr                   (i_cpu_addr),
        .cpu_wdata                  (i_cpu_wdata),
        .cpu_wstrb                  (i_cpu_wstrb),
        .cpu_rdata                  (i_cpu_rdata),
        .cpu_valid                  (i_cpu_valid),
        .cpu_ready                  (i_cpu_ready),

            // TODO: streaming interface as well... ?

        // -------------- memory --------------

        .ram_addr                   (i_ram_addr),
        .ram_wdata                  (i_ram_wdata),
        .ram_wstrb                  (i_ram_wstrb),
        .ram_rdata                  (i_ram_rdata),
        .ram_valid                  (i_ram_valid),
        .ram_ready                  (i_ram_ready),


        // -------------- ela probes --------------

        .watch_clear_async          (i_eio_out[0]),

        .probe_bus                  (i_probe_bus),
        .probe_watch                (i_probe_watch)
    );


    // ----------------------------------------------
    //  User
    // ----------------------------------------------

    user user_inst (
        .sysclk             (i_sysclk),
        .sysclk_resetn      (i_sysclk_resetn),

        .microsecond_tick   (i_microsecond_tick),
        .millisecond_tick   (i_millisecond_tick),
        .second_tick        (i_second_tick),

        .io                 (pad_io),

        .cpu_addr           (i_cpu_addr),
        .cpu_wdata          (i_cpu_wdata),
        .cpu_wstrb          (i_cpu_wstrb),
        .cpu_rdata          (i_cpu_rdata),
        .cpu_valid          (i_cpu_valid),
        .cpu_ready          (i_cpu_ready),

        .ram_addr           (i_ram_addr),
        .ram_wdata          (i_ram_wdata),
        .ram_wstrb          (i_ram_wstrb),
        .ram_rdata          (i_ram_rdata),
        .ram_valid          (i_ram_valid),
        .ram_ready          (i_ram_ready),

        .probe              (i_user_probe)
    );


    // ----------------------------------------------
    //  ELA Example
    // ----------------------------------------------

    generate
        if(EMBEDDED_LOGIC_ANALYZER) begin

            // ----------------------------------------------
            //  Internal signals (ELA-internal)
            // ----------------------------------------------

            // SAMPLE_W is the width captured per sample. NUM_CHANNELS is
            // a build-time MUX, not extra width - it gives N separate
            // SAMPLE_W buses and you capture one of them, chosen at arm
            // time. So the whole bus goes in SAMPLE_W, channels stay 1.

            // ---- user.sv's own probe: off by default -----------------
            //
            // Set ELA_USER_PROBE to 1 to capture user.sv's 16-bit probe
            // alongside the bus. That is the ONLY edit needed here - the
            // sample width and the concatenation both follow from it.
            //
            // Then add a user_probe entry to prog/epm11_bus.prob so
            // the host knows how to decode it - name user_probe, width
            // 16, lsb 128 - and change sample_width there to 144.
            //
            // Cost: no extra BSRAM (128 and 144 bits both need 8 blocks),
            // but readback goes from 4 words per sample to 5.

            localparam ELA_USER_PROBE   = 0;

            localparam ELA_SAMPLE_WIDTH = PROBE_BUS_W + (ELA_USER_PROBE * 16);
            localparam ELA_SAMPLE_DEPTH = 64;
            localparam ELA_CHANNELS     = 1;

            reg                                         i_sysclk_reset;

            reg [1:0]                                   i_buttons;

            always @(posedge i_sysclk) begin
                if (i_sysclk_resetn == 1'b0) begin
                    i_buttons   <= 0;
                end else begin
                    i_buttons   <= ~pad_user_buttons_n;
                end
            end

            // Built at full width, then sliced. With ELA_USER_PROBE at 0
            // the slice drops the user probe and synthesis prunes it.
            wire [PROBE_BUS_W+15:0] i_ela_sample = {i_user_probe, i_probe_bus};

            // ----------------------------------------------
            //  Embedded Logic Analyser
            // ----------------------------------------------

            assign i_sysclk_reset = ~i_sysclk_resetn;

            fcapz_ela_gowin #(
                .SAMPLE_W       (ELA_SAMPLE_WIDTH),
                .DEPTH          (ELA_SAMPLE_DEPTH),
                .NUM_CHANNELS   (ELA_CHANNELS),

                .STOR_QUAL      (1),
                    // NOTE: qualify capture with CHANGED on
                    // pclk, which is probe_bus[0]:
                    //
                    //   --stor-qual-mode 8 --stor-qual-mask 0x01
                    //
                    // That stores one sample per pclk edge.
                    // A free-running 51 MHz capture 64 deep
                    // spans 1.25 us, which a slow host burst
                    // will never fit into.
                    //
                    // It has to be a LOW bit: fcapz_ela.v
                    // zero-extends the qualification value
                    // and mask from 32-bit registers when
                    // SAMPLE_W > 32, so only bits below 32
                    // can ever be matched.

                .EIO_EN         (1),
                .EIO_IN_W       (PROBE_WATCH_W),
                .EIO_OUT_W      (8)
                    // NOTE: the four watched words are slow
                    // state, not waveform. EIO reads them on
                    // demand for no BSRAM, instead of storing
                    // the same value 64 times over.
            ) u_ela (
                .clk            (i_sysclk),
                    // NOTE: this clock must be
                    // at least ~10x the JTAG TCK
                    // (~2 MHz for EPM11)
                .jtag_activity  (i_jtag_activity),

                .sample_clk     (i_sysclk),
                .sample_rst     (i_sysclk_reset),
                .probe_in       (i_ela_sample[ELA_SAMPLE_WIDTH-1:0]),

                .eio_probe_in   (i_probe_watch),
                .eio_probe_out  (i_eio_out),
                    // NOTE: eio_out[0] re-zeroes the
                    // watched words over JTAG.

                .tms_pad_i      (tms_pad_i),
                .tck_pad_i      (tck_pad_i),
                .tdi_pad_i      (tdi_pad_i),
                .tdo_pad_o      (tdo_pad_o)
            );

            // NOTE: We control the
            // leds in this case
            // ---------------------

            always @(posedge i_sysclk) begin
                if (i_millisecond_tick == 1'b1) begin
                    if (i_millisecond_counter == 0 || i_millisecond_counter == 500) begin
                        i_ela_led[0] <= ~i_ela_led[0];
                    end
                end

                if (i_jtag_activity == 1'b1) begin
                    i_ela_led[1] <= 1'b1;
                end
                if (|i_millisecond_counter[6:0] == 1'b0) begin
                    i_ela_led[1] <= 0;
                end

                i_ela_led[2] <= i_buttons[1];

                if (i_sysclk_resetn == 1'b0) begin
                    i_ela_led <= 0;
                end
            end

            assign pad_led_n = ~(|i_ela_led);

        end else begin

            assign tdo_pad_o = 1'b0;

            assign pad_led_n = ~i_top_led;

            assign i_eio_out = 8'h00;
                // NOTE: no ELA, so nothing drives
                // the EIO outputs - keep watch_clear
                // from floating.
        end
    endgenerate


endmodule" >> $build_artifacts_directory"/"$top_wrapper_filename
